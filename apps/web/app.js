const languageSelect = document.querySelector("#language");
const form = document.querySelector("#ticket-form");
const photoInput = document.querySelector("#ticket-photo");
const photoPreview = document.querySelector("#photo-preview");
const previewImage = document.querySelector("#preview-image");
const resultMessage = document.querySelector("#result-message");
const resultMeta = document.querySelector("#result-meta");
const speechStatus = document.querySelector("#speech-status");
let currentObjectUrl = null;

function setLanguage(language) {
  const dictionary = translations[language] || translations.en;
  document.documentElement.lang = language;
  languageSelect.setAttribute("aria-label", dictionary.languageAriaLabel);
  document.querySelector("#lottery-name").placeholder = dictionary.lotteryPlaceholder;
  document.querySelector("#ticket-numbers").placeholder = dictionary.numbersPlaceholder;
  document.querySelector("#ticket-letters").placeholder = dictionary.lettersPlaceholder;
  previewImage.alt = dictionary.previewAlt;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) element.textContent = dictionary[key];
  });
}

languageSelect.addEventListener("change", () => {
  if ("speechSynthesis" in window) window.speechSynthesis.cancel();
  speechStatus.textContent = "";
  setLanguage(languageSelect.value);
});

photoInput.addEventListener("change", () => {
  const file = photoInput.files && photoInput.files[0];
  if (currentObjectUrl) URL.revokeObjectURL(currentObjectUrl);
  currentObjectUrl = null;
  if (!file) {
    photoPreview.hidden = true;
    previewImage.removeAttribute("src");
    return;
  }
  const dictionary = translations[languageSelect.value] || translations.en;
  const photoStatus = document.querySelector("#photo-status");
  photoStatus.textContent = "";
  if (!file.type.startsWith("image/")) {
    photoInput.value = "";
    photoPreview.hidden = true;
    photoStatus.textContent = dictionary.photoInvalid;
    return;
  }
  if (file.size > 10 * 1024 * 1024) {
    photoInput.value = "";
    photoPreview.hidden = true;
    photoStatus.textContent = dictionary.photoTooLarge;
    return;
  }
  currentObjectUrl = URL.createObjectURL(file);
  previewImage.onload = () => {
    if (previewImage.naturalWidth * previewImage.naturalHeight > 20000000) {
      URL.revokeObjectURL(currentObjectUrl);
      currentObjectUrl = null;
      photoInput.value = "";
      previewImage.removeAttribute("src");
      photoPreview.hidden = true;
      photoStatus.textContent = dictionary.photoTooLarge;
    }
  };
  previewImage.onerror = () => {
    if (currentObjectUrl) URL.revokeObjectURL(currentObjectUrl);
    currentObjectUrl = null;
    photoInput.value = "";
    previewImage.removeAttribute("src");
    photoPreview.hidden = true;
    photoStatus.textContent = dictionary.photoInvalid;
  };
  previewImage.src = currentObjectUrl;
  photoPreview.hidden = false;
});

document.querySelector("#remove-photo").addEventListener("click", () => {
  photoInput.value = "";
  document.querySelector("#photo-status").textContent = "";
  if (currentObjectUrl) URL.revokeObjectURL(currentObjectUrl);
  currentObjectUrl = null;
  previewImage.removeAttribute("src");
  photoPreview.hidden = true;
});

form.addEventListener("submit", (event) => {
  event.preventDefault();
  const dictionary = translations[languageSelect.value] || translations.en;
  if (!form.reportValidity()) return;
  document.querySelector("#result-panel h2").textContent = dictionary.statusTitle;
  resultMessage.textContent = dictionary.statusMessage;
  resultMeta.textContent = dictionary.statusMeta;
  speechStatus.textContent = "";
  document.querySelector("#result-panel").scrollIntoView({ behavior: "smooth", block: "center" });
});

document.querySelector("#speak-result").addEventListener("click", () => {
  const dictionary = translations[languageSelect.value] || translations.en;
  if (!("speechSynthesis" in window) || typeof SpeechSynthesisUtterance === "undefined") {
    speechStatus.textContent = dictionary.speechUnavailable;
    return;
  }
  const text = [document.querySelector("#result-panel h2").textContent, resultMessage.textContent, resultMeta.textContent].join(". ");
  if (!text.trim()) {
    speechStatus.textContent = dictionary.noMessage;
    return;
  }
  window.speechSynthesis.cancel();
  const locale = ({ en: "en-LK", si: "si-LK", ta: "ta-LK" })[languageSelect.value] || "en";
  const baseLanguage = locale.split("-")[0].toLowerCase();
  const voice = window.speechSynthesis.getVoices().find((candidate) => {
    const candidateLanguage = candidate.lang.toLowerCase();
    return candidateLanguage === locale.toLowerCase() || candidateLanguage.startsWith(baseLanguage + "-");
  });
  if (!voice) {
    speechStatus.textContent = dictionary.speechUnavailable;
    return;
  }
  const utterance = new SpeechSynthesisUtterance(text);
  utterance.lang = locale;
  utterance.voice = voice;
  utterance.onerror = () => { speechStatus.textContent = dictionary.speechUnavailable; };
  utterance.onend = () => { speechStatus.textContent = ""; };
  window.speechSynthesis.speak(utterance);
  speechStatus.textContent = dictionary.speechStarted;
});

document.querySelector("#stop-speech").addEventListener("click", () => {
  if ("speechSynthesis" in window) window.speechSynthesis.cancel();
  speechStatus.textContent = "";
});

document.addEventListener("visibilitychange", () => {
  if (document.hidden && "speechSynthesis" in window) window.speechSynthesis.cancel();
});

